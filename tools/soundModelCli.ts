/**
 * Command line for tools/soundModel.ts (run through tools/sound-model.mjs). Reference recordings are
 * given as paths; the output is a model module in src/audio/models/.
 *
 *   onsets  --in rec.wav [--lo 150] [--hi 4000] [--rise 15] [--gap 0.25]
 *   print   --in rec.wav --out src/audio/models/x.ts --name X --at t0,t1,… --length d
 *           [--step 0.02] [--floor | --floor-from t0,t1] [--bands lo-hi] [--transients]
 *           [--desc "…"] [--preview dir]
 *   texture --in rec.wav --out src/audio/models/x.ts --name X --from t0 --to t1
 *           [--over 8] [--clicks lo-hi] [--desc "…"] [--preview dir]
 */
import { bandLevels, encodeLevels, encodePrint, encodeWav, fitPrint, fitTexture, floorLevels, parseWav, segmentLevels, synthPrint } from './soundModel';
import { synthTexture, THIRD_OCTAVES } from '../src/audio/synth/spectral';
import { rng } from '../src/audio/dsp';

/** File access, provided by the Node runner (tools/sound-model.mjs). */
export interface Io {
  args: string[];
  read(path: string): Uint8Array;
  write(path: string, data: Uint8Array | string): void;
  log(line: string): void;
}

export function run(io: Io): void {
const [cmd, ...rest] = io.args;
const readWav = (p: string) => parseWav(io.read(p));
const writeWav = (p: string, x: Float32Array, sr: number) => io.write(p, encodeWav(x, sr));
const join = (dir: string, file: string) => `${dir.replace(/\/$/, '')}/${file}`;
const opts = new Map<string, string>();
for (let i = 0; i < rest.length; i++) {
  if (!rest[i].startsWith('--')) continue;
  const next = rest[i + 1];
  if (next === undefined || next.startsWith('--')) opts.set(rest[i].slice(2), 'true');
  else {
    opts.set(rest[i].slice(2), next);
    i++;
  }
}
const need = (k: string) => {
  const v = opts.get(k);
  if (v === undefined) throw new Error(`--${k} is required`);
  return v;
};
const num = (k: string, d: number) => (opts.has(k) ? Number(opts.get(k)) : d);
const list = (v: readonly number[], d: number) => `[${v.map((x) => fmt(x, d)).join(', ')}]`;

const header = (desc: string) =>
  `/**\n * ${desc}\n *\n * Generated by tools/sound-model.mjs: a model fitted to a reference recording (its measured\n * spectro-temporal envelope or spectrum), not audio. Regenerate rather than edit.\n */\n`;

function fmt(v: number, d = 4): string {
  return Number(v.toFixed(d)).toString();
}

if (cmd === 'onsets') {
  const a = readWav(need('in'));
  const lo = num('lo', 150);
  const hi = num('hi', 4000);
  const rise = num('rise', 15);
  const gap = num('gap', 0.25);
  const times: number[] = [];
  for (let t = 0.005; t < a.x.length / a.sr; t += 0.0025) times.push(t);
  const lv = bandLevels(a, times);
  const sel = THIRD_OCTAVES.map((f, b) => (f >= lo && f <= hi ? b : -1)).filter((b) => b >= 0);
  const e = lv.map((row) => 10 * Math.log10(sel.reduce((s, b) => s + Math.pow(10, row[b] / 10), 0)));
  const sorted = [...e].sort((p, q) => p - q);
  const floor = sorted[Math.floor(sorted.length * 0.1)];
  let last = -1;
  for (let k = 1; k < e.length; k++) {
    if (e[k] > floor + rise && e[k - 1] <= floor + rise && times[k] - last > gap) {
      last = times[k];
      // Back up to where the rise starts.
      let j = k;
      while (j > 0 && e[j - 1] < e[j] && e[j - 1] > floor + 3) j--;
      io.log(`${times[j].toFixed(4)}  peak +${(Math.max(...e.slice(k, k + 40)) - floor).toFixed(1)} dB`);
    }
  }
} else if (cmd === 'print') {
  const a = readWav(need('in'));
  const at = need('at').split(',').map(Number);
  const length = Number(need('length'));
  const step = num('step', 0.02);
  const ff = opts.has('floor-from') ? need('floor-from').split(',').map(Number) : null;
  const floor = ff ? segmentLevels(a, ff[0], ff[1]) : opts.has('floor') ? floorLevels(a) : null;
  const bands = opts.has('bands') ? (need('bands').split('-').map(Number) as [number, number]) : undefined;
  const name = need('name');
  const fits = at.map((t0) => fitPrint(a, t0, length, floor, { maxStep: step, transients: opts.has('transients'), bands }));
  fits.forEach((f, i) => io.log(`${name}[${i}] at ${at[i]}: ${f.print.times.length} knots, fit error ${f.report.error.toFixed(2)} dB (${f.report.history.map((h) => h.toFixed(1)).join(' → ')})`));
  const body = fits
    .map((f) => {
      const e = encodePrint(f.print);
      return `  decodePrint(\n    ${list(f.print.times, 5)},\n    ${JSON.stringify(e.data)},\n    ${e.offset},${f.print.onsets ? `\n    [${f.print.onsets.map(([t, st, ct]) => `[${fmt(t, 5)}, strike(${JSON.stringify(encodeLevels(st, e.offset))}, ${e.offset}), ${fmt(ct ?? 0, 4)}]`).join(', ')}],` : ''}\n  ),`;
    })
    .join('\n');
  const src = `${header(opts.get('desc') ?? name)}import { decodePrint, decodeStrike as strike, type SpectralPrint } from '../synth/spectral';\n\nexport const ${name}: readonly SpectralPrint[] = [\n${body}\n];\n`;
  io.write(need('out'), src);
  io.log(`wrote ${need('out')} (${(src.length / 1024).toFixed(1)} KB)`);
  if (opts.has('preview')) {
    const dir = need('preview');
    fits.forEach((f, i) => {
      const t0 = at[i];
      const seg = a.x.slice(Math.round(t0 * a.sr), Math.round((t0 + length) * a.sr));
      writeWav(join(dir, `${name}-${i}-ref.wav`), seg, a.sr);
      writeWav(join(dir, `${name}-${i}-clone.wav`), synthPrint(f.print, a.sr, 4242 + i, 0), a.sr);
    });
  }
} else if (cmd === 'texture') {
  const a = readWav(need('in'));
  const from = Number(need('from'));
  const to = Number(need('to'));
  const name = need('name');
  const clickBand = opts.has('clicks') ? (need('clicks').split('-').map(Number) as [number, number]) : undefined;
  const { model, report } = fitTexture(a, from, to, 4, num('over', 8), clickBand);
  io.log(`${name}: ${model.floor.length} floor points, ${model.lines.length} lines, floor fit error ${report.error.toFixed(2)} dB`);
  const floor = model.floor.map(([f, v]) => `[${fmt(f, 1)}, ${fmt(v, 1)}]`).join(', ');
  const lines = model.lines.map(([f, v, bw]) => `[${fmt(f, 2)}, ${fmt(v, 1)}, ${fmt(bw, 2)}]`).join(', ');
  const ck = model.clicks;
  const clicks = ck ? `\n  clicks: { clustersPerSecond: ${fmt(ck.clustersPerSecond, 2)}, perCluster: ${list(ck.perCluster, 0)}, spacing: ${list(ck.spacing, 4)}, excess: ${list(ck.excess, 1)}, band: ${list(ck.band, 0)} },` : '';
  const src = `${header(opts.get('desc') ?? name)}import type { TextureModel } from '../synth/spectral';\n\nexport const ${name}: TextureModel = {\n  floor: [${floor}],\n  lines: [${lines}],${clicks}\n};\n`;
  io.write(need('out'), src);
  io.log(`wrote ${need('out')} (${(src.length / 1024).toFixed(1)} KB)`);
  if (opts.has('preview')) {
    const dir = need('preview');
        writeWav(join(dir, `${name}-ref.wav`), a.x.slice(Math.round(from * a.sr), Math.round(to * a.sr)), a.sr);
    writeWav(join(dir, `${name}-clone.wav`), synthTexture(model, 18, a.sr, rng(5)), a.sr);
  }
} else {
  io.log('commands: onsets, print, texture (see tools/soundModelCli.ts)');
}
}
